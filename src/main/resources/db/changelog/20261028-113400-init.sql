CREATE TABLE IF NOT EXISTS public.users
(
    id         VARCHAR(255) PRIMARY KEY,
    dob        DATE,
    first_name VARCHAR(255),
    last_name  VARCHAR(255),
    password   VARCHAR(255),
    username   VARCHAR(255),
    created_at DATE,
    status     VARCHAR(255),
    updated_at DATE,
    url_avt    VARCHAR(255)
);



-- =====================================================
-- 2. CONVERSATIONS
-- Cuộc trò chuyện riêng tư hoặc nhóm
-- =====================================================

CREATE TABLE IF NOT EXISTS public.conversations
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    type       VARCHAR(20) NOT NULL,
    name       VARCHAR(255),
    avatar_url VARCHAR(500),
    created_by BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,

    CONSTRAINT fk_conversations_created_by
        FOREIGN KEY (created_by)
            REFERENCES public.users(id)
);




-- =====================================================
-- 3. CONVERSATION_MEMBERS
-- Thành viên của từng cuộc trò chuyện
-- =====================================================

CREATE TABLE IF NOT EXISTS public.conversation_members
(
    conversation_id       BIGINT NOT NULL,
    user_id               BIGINT NOT NULL,
    role                  VARCHAR(30) DEFAULT 'MEMBER',
    joined_at             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at               TIMESTAMP,
    last_read_message_id  BIGINT,
    is_muted              BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_conversation_members
        PRIMARY KEY (conversation_id, user_id),

    CONSTRAINT fk_members_conversation
        FOREIGN KEY (conversation_id)
            REFERENCES public.conversations(id),

    CONSTRAINT fk_members_user
        FOREIGN KEY (user_id)
            REFERENCES public.users(id)
);


-- =====================================================
-- 4. MESSAGES
-- Nội dung tin nhắn
-- =====================================================

CREATE TABLE IF NOT EXISTS public.messages
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_id       BIGINT NOT NULL,
    content         TEXT,
    message_type    VARCHAR(30) NOT NULL DEFAULT 'TEXT',
    reply_to_message_id BIGINT,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP,
    deleted_at      TIMESTAMP,

    CONSTRAINT fk_messages_conversation
        FOREIGN KEY (conversation_id)
            REFERENCES public.conversations(id),

    CONSTRAINT fk_messages_sender
        FOREIGN KEY (sender_id)
            REFERENCES public.users(id),

    CONSTRAINT fk_messages_reply
        FOREIGN KEY (reply_to_message_id)
            REFERENCES public.messages(id)
);


-- =====================================================
-- 5. MESSAGE_ATTACHMENTS
-- Ảnh, video, file đính kèm
-- =====================================================

CREATE TABLE IF NOT EXISTS public.message_attachments
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    message_id BIGINT NOT NULL,
    file_url   VARCHAR(1000) NOT NULL,
    file_name  VARCHAR(255),
    file_type  VARCHAR(100),
    file_size  BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_attachments_message
        FOREIGN KEY (message_id)
            REFERENCES public.messages(id)
            ON DELETE CASCADE
);


-- =====================================================
-- 6. MESSAGE_RECEIPTS
-- Trạng thái nhận và đọc tin nhắn
-- =====================================================

CREATE TABLE IF NOT EXISTS public.message_receipts
(
    message_id  BIGINT NOT NULL,
    user_id     BIGINT NOT NULL,
    delivered_at TIMESTAMP,
    read_at     TIMESTAMP,

    CONSTRAINT pk_message_receipts
        PRIMARY KEY (message_id, user_id),

    CONSTRAINT fk_receipts_message
        FOREIGN KEY (message_id)
            REFERENCES public.messages(id)
            ON DELETE CASCADE,

    CONSTRAINT fk_receipts_user
        FOREIGN KEY (user_id)
            REFERENCES public.users(id)
);


-- =====================================================
-- 7. MESSAGE_REACTIONS
-- Cảm xúc trên tin nhắn
-- =====================================================

CREATE TABLE IF NOT EXISTS public.message_reactions
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    message_id BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    reaction   VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reactions_message
        FOREIGN KEY (message_id)
            REFERENCES public.messages(id)
            ON DELETE CASCADE,

    CONSTRAINT fk_reactions_user
        FOREIGN KEY (user_id)
            REFERENCES public.users(id),

    CONSTRAINT uq_message_reaction_user
        UNIQUE (message_id, user_id)
);


-- =====================================================
-- 8. INDEXES
-- Tối ưu truy vấn danh sách tin nhắn
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_messages_conversation_created
    ON public.messages (conversation_id, created_at, id);

CREATE INDEX IF NOT EXISTS idx_conversation_members_user
    ON public.conversation_members (user_id);

CREATE INDEX IF NOT EXISTS idx_messages_sender
    ON public.messages (sender_id);

CREATE INDEX IF NOT EXISTS idx_message_receipts_user
    ON public.message_receipts (user_id);
